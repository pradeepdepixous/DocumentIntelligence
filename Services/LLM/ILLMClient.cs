namespace PixousDocIntelligence.Services.LLM;

/// <summary>
/// Provider-agnostic abstraction for generative AI and reasoning language models.
/// Enables dynamic switching between Google Gemini, OpenAI, and future providers.
/// </summary>
public interface ILLMClient
{
    /// <summary>
    /// The unique name of the LLM provider (e.g. 'Gemini', 'OpenAI', 'Anthropic').
    /// </summary>
    string ProviderName { get; }

    /// <summary>
    /// The active model name (e.g. 'gemini-flash-latest', 'gpt-4o-mini', 'gpt-4o').
    /// </summary>
    string ModelName { get; }

    /// <summary>
    /// Executes a completion request given a system instruction and user prompt.
    /// </summary>
    /// <param name="systemInstruction">High-level persona and behavioral guidance.</param>
    /// <param name="userPrompt">User query, document payload, or checklist.</param>
    /// <param name="requireJson">Whether the output must be strictly valid JSON.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The raw text or JSON response content generated by the model.</returns>
    Task<string> GenerateContentAsync(
        string systemInstruction, 
        string userPrompt, 
        bool requireJson = false, 
        CancellationToken cancellationToken = default);
}
